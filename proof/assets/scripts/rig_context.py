#!/usr/bin/env python3
"""Write the rules every rig worker must have into the one place Claude Code
loads without being told to: a CLAUDE.md in the directory ABOVE the rig clones.
A script — no agent, no model, no tokens.

    rig_context.py [--print]

A worker starts in its rig's clone, not in the workspace root, so none of the
workspace constitution is on its path; in the first dispatched batch two of five
workers opened it and none opened a doctrine body. Claude Code reads CLAUDE.md
from every directory above the working one, so one generated file covers every
rig, and nothing depends on a worker obeying a sentence in a step.

It is deliberately LEAN. Knowledge is spent once, by whoever plans an item, and
arrives in the bead; this file carries only the invariant rules no bead can —
and every conversation pays for each line of it on every turn. So it copies a
short allow-list of sections from the orchestrator's AGENTS.md at origin/main
(copied, never @-imported: an import from outside the project can raise an
approval dialog, and gc answers dialogs with a bare Enter). A section that is
neither allowed nor skipped below is NEW: it is copied, and logged, because a
rule nobody classified is safer loaded than lost.
"""
from __future__ import annotations

import os
import re
import sys

import factory_lib as fl
from factory_lib import admit

ME = "rig-context"
# heading -> None (whole block) or the bold lead-ins of the paragraphs to keep
COPY = {
    "Active Project Routing": ("**Naming:**", "**Environment variables:**"),
    "Cross-cutting safety guardrails": None,
    "Confirmed shared resources (owners)": None,
    "Validation evidence belongs to one tree": None,
}
# Governs the workspace root, a claim, a landing or the docs system — all of which
# admission, the dispatcher and the completer do for a packet. Or arrives per
# packet: admission puts the doctrine a write_scope selects into the work bead.
SKIP = {
    "Shell / environment", "Repository lifecycle is explicit", "Commit messages",
    "Conditional doctrine", "The shared checkout goes stale silently", "Documentation System",
    "Work in a worktree, at the standard location", "Commit & Push Default",
    "Every failing check has an owner", "CI waiting must not consume agent turns",
    "Orchestrator work must land on `main`", "Do NOT auto-commit when", "Docs-update obligation",
    "Public docs release obligation", "Where to write", "Validation",
}
LINK = re.compile(r"\]\((?!https?://|#|/|mailto:)([^)\s]+)\)")


def blocks(text):
    """[(heading, body)] at ## / ### granularity; the preamble above the first is dropped."""
    found, heading, body = [], None, []
    for line in text.splitlines():
        match = re.match(r"^#{2,3} (.+?)\s*$", line)
        if match:
            if heading is not None:
                found.append((heading, "\n".join(body).strip("\n")))
            heading, body = match.group(1), []
        elif heading is not None:
            body.append(line)
    if heading is not None:
        found.append((heading, "\n".join(body).strip("\n")))
    return found


def build(backlog_clone, sha, rig_paths):
    text = open(os.path.join(backlog_clone, "AGENTS.md"), encoding="utf-8").read()
    rigs_dir = os.path.dirname(backlog_clone)

    def absolute(match):
        target = match.group(1)
        member = re.match(r"repos/([^/]+)/(.*)", target)
        if member and os.path.isdir(os.path.join(rigs_dir, member.group(1))):
            return "](%s)" % os.path.join(rigs_dir, member.group(1), member.group(2))
        return "](%s)" % os.path.join(backlog_clone, target)

    copied, new, seen = [], [], set()
    for heading, body in blocks(text):
        seen.add(heading)
        if heading in SKIP:
            continue
        if heading not in COPY:
            new.append(heading)
        keep = COPY.get(heading)
        if keep:
            body = "\n\n".join(p for p in re.split(r"\n\s*\n", body) if p.lstrip().startswith(keep))
        body = re.sub(r"\n---\s*$", "", body.strip()).strip()
        if body:
            copied.append("## %s\n\n%s" % (heading, LINK.sub(absolute, body)))
    missing = sorted(set(COPY) - seen)

    unloaded = sorted(name for name, path in rig_paths.items()
                      if path and os.path.isfile(os.path.join(path, "AGENTS.md"))
                      and not os.path.isfile(os.path.join(path, "CLAUDE.md")))
    head = [
        "# Workspace rules for a worker in a PROOF Gas City rig",
        "",
        "<!-- GENERATED by gascity/packs/proof/assets/scripts/rig_context.py from %s/AGENTS.md @ %s."
        % (backlog_clone, sha[:12]),
        "     Do not edit: the next factory pass rewrites it. -->",
        "",
        "You are in a Gas City-owned clone under `%s`, not in the liskov workspace root, so the" % rigs_dir,
        "workspace constitution is not on your path. The sections below are copied from it and bind you.",
        "They are deliberately few: **your work bead is meant to be enough.** It names the backlog item,",
        "the documents worth reading, and the conditional doctrine a script chose from the item's",
        "write_scope. Read what it names; do not go reading the workspace to be safe.",
        "",
        "- **What you may DO is set by the step you are executing and your packet's landing",
        "  authorization** — nothing here widens it. Where a copied rule speaks of claiming, creating a",
        "  worktree, updating orchestrator docs, landing or completing an item: admission, the dispatcher",
        "  and the completer do those. The repository's own `AGENTS.md` governs local conventions where",
        "  it has one; many member repositories have none, and that is expected, not a reason to stop.",
        "- **The item's `write_scope` is intent, not a fence** (ADR-0159). Edit what your change forces",
        "  beyond it — a companion, a census, a ratchet, a module declaration — and name those paths in",
        "  the work bead's notes; do not mail them, the daily report lists them. Stop only for a",
        "  reserved path, a protected one the scope did not declare (CI workflows, Fly/deploy config, `.env*`, `secrets/`, and in the orchestrator `gascity/`,",
        "  `scripts/`, `AGENTS.md`, `docs/meta/`), or a review-substring path when you have no reviewer.",
        "- Name your packet (`BKLG-…`) and any ADR you relied on in the body of every commit.",
        "- The orchestrator clone `%s` is **read-only** for you unless it is your packet's" % backlog_clone,
        "  repository. The full constitution is its `AGENTS.md`; you should not need it.",
        "- **A bead that arrives with an EMPTY description is a re-issued iteration** of a checked step",
        "  (`implement`, `land`, `review-cycle`): gc 1.4.2 re-issues it without its text. Its instructions",
        "  are the sibling whose `gc.step_ref` ends `<step>.spec` under the same workflow root:",
        "  `gc bd list --all --metadata-field gc.root_bead_id=<root id> --json --limit=0`. That bead's",
        "  description is the step's spec as JSON; its `description` field is your instructions — for a",
        "  child step (`implement`'s `code`, `review-cycle`'s `apply-findings`), the entry in its `children`",
        "  whose `id` your bead's `gc.step_ref` ends with. Never guess what an empty bead wants.",
        "- **Close every hard failure with the helper, never by hand:** `( cd \"$GC_RIG_ROOT\" &&",
        "  \"$GC_CITY\"/packs/proof/assets/scripts/close-hard.sh <bead id> <failure_reason> )`. A hard failure",
        "  ends a checked loop on the first occurrence in the qualified engine. Investigate and repair",
        "  what your packet authorizes before closing hard. Preserve a concise checkpoint and name",
        "  any missing decision or external input. Never change a controller's attempt budget.",
        "- When something surprises you — a ratchet, a registry, a migration number, a CI quirk — grep",
        "  `%s/<your rig>/` before working it out again: it indexes traps this" % os.path.join(rigs_dir, "knowledge"),
        "  workspace has already paid for. It is there to be searched, not read.",
    ]
    if unloaded:
        head += ["- **In %s, `AGENTS.md` is NOT auto-loaded** (the repository has no `CLAUDE.md`). Read it in your"
                 % ", ".join("`%s`" % name for name in unloaded),
                 "  packet worktree before anything else."]
    tail = ["", "---", "", "Not copied — they govern the workspace root, a claim, a landing or the docs system, or reach you",
            "per packet in the work bead: " + "; ".join(sorted(SKIP & seen)) + "."]
    return "\n".join(head + [""] + ["\n\n".join(copied)] + tail) + "\n", new, missing


def main(argv):
    city = fl.city_dir()
    rigs = admit.load_rigs(city)
    backlog = admit.backlog_clone_of(rigs)
    sha = admit.refresh_backlog_clone(backlog)
    owned = {}
    for rig in sorted(rigs):
        try:
            owned[rig] = admit.owned_clone(rigs, rig)
        except fl.Refused:
            continue
    parents = {os.path.dirname(path.rstrip("/")) for path in owned.values()}
    if len(parents) != 1:
        raise fl.Refused("the owned rig clones do not share one parent directory (%s); a single CLAUDE.md "
                         "cannot cover them" % ", ".join(sorted(parents)))
    # A rig's session starts in the clone's main checkout: keep it current so a
    # CLAUDE.md the repository gains is the one the session loads. Fast-forward
    # or nothing, and without a fetch — workers fetch in worktrees of this clone.
    for path in owned.values():
        if path != backlog and fl.sh(["git", "-C", path, "rev-parse", "--abbrev-ref", "HEAD"]).stdout.strip() == "main":
            fl.sh(["git", "-C", path, "merge", "--quiet", "--ff-only", "origin/main"])
    text, new, missing = build(backlog, sha, owned)
    if "--print" in argv:
        sys.stdout.write(text)
        return 0
    target = os.path.join(parents.pop(), "CLAUDE.md")
    if not os.path.isfile(target) or open(target, encoding="utf-8").read() != text:
        tmp = target + ".tmp"
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.replace(tmp, target)
        fl.log(ME, "wrote %s from AGENTS.md @ %s (%d bytes)" % (target, sha[:10], len(text)))
    # Codex reads instruction files from its project root down, and the root is
    # the nearest root marker. city.toml makes this file the ONLY marker for the
    # codex provider, so the walk starts here and picks up the CLAUDE.md above.
    marker = os.path.join(os.path.dirname(target), ".gascity-rigs-root")
    if not os.path.isfile(marker):
        open(marker, "w", encoding="utf-8").close()
        fl.log(ME, "wrote %s (Codex project-root marker)" % marker)
    # asdf resolves a tool version from a `.tool-versions` on the path from the
    # working directory upward. A rig clone is outside the workspace tree that
    # carries one, so `node` there fails with "No version is set". Same trick as
    # CLAUDE.md: one copy above every rig, kept equal to the workspace's.
    versions = os.path.join(backlog, ".tool-versions")
    if os.path.isfile(versions):
        wanted = open(versions, encoding="utf-8").read()
        beside = os.path.join(os.path.dirname(target), ".tool-versions")
        if not os.path.isfile(beside) or open(beside, encoding="utf-8").read() != wanted:
            with open(beside, "w", encoding="utf-8") as fh:
                fh.write(wanted)
            fl.log(ME, "wrote %s (%s)" % (beside, " ".join(wanted.split())))
    for heading in new:
        fl.log(ME, "AGENTS.md has a section nobody classified, copied to be safe: %r — add it to COPY or SKIP" % heading)
    for heading in missing:
        fl.log(ME, "AGENTS.md no longer has the section %r that rigs were given; it was renamed or removed" % heading)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except fl.Refused as why:
        fl.log(ME, "stopped — %s" % why)
        sys.exit(1)
